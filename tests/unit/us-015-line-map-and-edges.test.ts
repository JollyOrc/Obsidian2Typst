describe('US-015 AC-12 no silent loss of a node', {timeout: 60_000}, () => {
  it('US-015 AC-12: the coverage note contains every node kind of the tree, so the test below is complete', () => {
    const used = new Set(
      all(parse(COVERAGE_NOTE).root).map((n) => n.kind as string),
    );
    const missing = [...kindsOfTree()].filter((k) => !used.has(k));
    expect(kindsOfTree().size).toBeGreaterThanOrEqual(25);
    expect(missing).toEqual([]);
  });

  it('US-015 AC-12: has an emitter for every node kind: the coverage note reports no NODE_UNSUPPORTED', async () => {
    const result = await run(COVERAGE_NOTE);
    expect(
      result.warnings.filter((w) => w.code === 'NODE_UNSUPPORTED'),
    ).toEqual([]);
  });

  it('US-015 AC-12: the sample note reports no NODE_UNSUPPORTED either', async () => {
    const real = readSample('Book.md');
    const result = await run(real, {}, [NOTE_PATH]);
    expect(
      result.warnings.filter((w) => w.code === 'NODE_UNSUPPORTED'),
    ).toEqual([]);
  });

  it('US-015 AC-12: emits the text and NODE_UNSUPPORTED with the kind and line for a block kind without an emitter', () => {
    const ctx = new EmitContext();
    const future = {
      kind: 'future-block',
      line: 7,
      children: [{kind: 'text', line: 7, value: 'kept text'}],
    } as unknown as BlockNode;
    const typ = emitBlocks([future], ctx);
    expect(typ).toContain('kept text');
    expect(ctx.finish()).toEqual([
      {
        code: 'NODE_UNSUPPORTED',
        message: 'No emitter for future-block; its text is kept',
        line: 7,
      },
    ]);
  });

  it('US-015 AC-12: keeps the value of a future block kind as escaped text', () => {
    const ctx = new EmitContext();
    const future = {
      kind: 'future-block',
      line: 4,
      value: 'a #b',
    } as unknown as BlockNode;
    expect(emitBlocks([future], ctx)).toBe('a \\#b');
    expect(ctx.finish().map((w) => w.code)).toEqual(['NODE_UNSUPPORTED']);
  });

  it('US-015 AC-12: a future inline kind inside a paragraph keeps its text around it and reports once', () => {
    const ctx = new EmitContext();
    const para = {
      kind: 'paragraph',
      line: 3,
      children: [
        {kind: 'text', line: 3, value: 'before '},
        {kind: 'future-inline', line: 3, value: 'kept'},
        {kind: 'text', line: 3, value: ' after'},
      ],
    } as unknown as BlockNode;
    const typ = emitBlocks([para], ctx);
    expect(typ).toContain('before');
    expect(typ).toContain('after');
    const warnings = ctx.finish();
    expect(warnings).toHaveLength(1);
    expect(warnings[0]).toMatchObject({code: 'NODE_UNSUPPORTED', line: 3});
    expect(warnings[0]?.message).toContain('future-inline');
  });
});
