const HEADER =
  '// Generated by Obsidian2Typst from "Rules.md". Regenerated on every export.';

describe('US-015 AC-8 line map', () => {
  it('US-015 AC-8: returns the line map of the composed example', async () => {
    const {lineMap} = await run(COMPOSED_NOTE);
    expect(lineMap).toEqual([
      {typLine: 13, sourceLine: 1},
      {typLine: 15, sourceLine: 3},
      {typLine: 17, sourceLine: 5},
      {typLine: 19, sourceLine: 7},
      {typLine: 20, sourceLine: 8},
      {typLine: 22, sourceLine: 10},
      {typLine: 24, sourceLine: 12},
      {typLine: 27, sourceLine: 12},
      {typLine: 28, sourceLine: 14},
    ]);
  });

  it('US-015 AC-8: without the image and its helper the lines move up by 8 after the image and by 6 before it', async () => {
    const note = COMPOSED_NOTE.replace('![Map](assets/map.png)\n\n', '');
    const {lineMap} = await run(note);
    expect(lineMap.map((e) => e.typLine)).toEqual([
      7, 9, 11, 13, 14, 16, 19, 20,
    ]);
    expect(lineMap.map((e) => e.sourceLine)).toEqual([
      1, 3, 5, 7, 8, 10, 10, 12,
    ]);
  });

  const MIXED = [
    '---', // 1
    'title: x', // 2
    '---', // 3
    '', // 4
    '# H', // 5
    '', // 6
    '> quote one', // 7
    '> two', // 8
    '', // 9
    '- a', // 10
    '  - b', // 11
    '- c', // 12
    '', // 13
    '```js', // 14
    'let x = 1;  ', // 15
    '```', // 16
    '', // 17
    '---', // 18
    '', // 19
    'Para[^n]', // 20
    '', // 21
    '[^n]: foot', // 22
    '', // 23
    '2. one', // 24
    '3. two', // 25
  ].join('\n');

  it('US-015 AC-8: has one entry for a heading, a quote and its paragraph, items, code, rule and paragraph, at the first line of the block, after a frontmatter', async () => {
    const {typ, lineMap} = await run(MIXED);
    expect(lineMap).toEqual([
      {typLine: 7, sourceLine: 5},
      {typLine: 9, sourceLine: 7},
      {typLine: 10, sourceLine: 7},
      {typLine: 14, sourceLine: 10},
      {typLine: 15, sourceLine: 11},
      {typLine: 16, sourceLine: 12},
      {typLine: 18, sourceLine: 14},
      {typLine: 22, sourceLine: 18},
      {typLine: 24, sourceLine: 20},
      {typLine: 26, sourceLine: 24},
      {typLine: 27, sourceLine: 25},
    ]);
    const lines = typ.split('\n');
    expect(lines[6]).toBe('= H <h-h>');
    expect(lines[8]).toBe('#quote(block: true)[');
    expect(lines[17]).toBe('```js');
    expect(lines[21]).toBe('#line(length: 100%)');
    expect(lines[25]).toBe('2. one');
  });

  it('US-015 AC-8: has an entry for the table and for every row, header row first', async () => {
    const note = '| a | b |\n|--|--|\n| 1 | 2 |\n| 3 | 4 |\n| 5 | 6 |';
    const {typ, lineMap} = await run(note);
    const lines = typ.split('\n');
    const table = lines.indexOf('#table(') + 1;
    expect(lineMap).toEqual([
      {typLine: table, sourceLine: 1},
      {typLine: table + 3, sourceLine: 1},
      {typLine: table + 4, sourceLine: 3},
      {typLine: table + 5, sourceLine: 4},
      {typLine: table + 6, sourceLine: 5},
    ]);
    expect(lines[table + 2]).toBe('  table.header([a], [b]),');
    expect(lines[table + 3]).toBe('  [1], [2],');
  });

  it('US-015 AC-8: has at most one entry per typLine; the innermost block wins (item and its paragraph in a loose list)', async () => {
    const {lineMap, typ} = await run('- a\n\n- b\n\n  more');
    const lines = lineMap.map((e) => e.typLine);
    expect(new Set(lines).size).toBe(lines.length);
    const first = typ.split('\n').indexOf('- a') + 1;
    expect(lineMap[0]).toEqual({typLine: first, sourceLine: 1});
  });

  it('US-015 AC-8: the innermost block wins when an item and its first paragraph start on different source lines', async () => {
    const {typ, lineMap} = await run('-\n  foo');
    const line = typ.split('\n').indexOf('- foo') + 1;
    expect(lineMap).toEqual([{typLine: line, sourceLine: 2}]);
  });

  it('US-015 AC-8: has an entry for an empty item', async () => {
    const {typ, lineMap} = await run('- a\n-\n- c');
    const first = typ.split('\n').indexOf('- a') + 1;
    expect(lineMap).toEqual([
      {typLine: first, sourceLine: 1},
      {typLine: first + 1, sourceLine: 2},
      {typLine: first + 2, sourceLine: 3},
    ]);
  });

  it('US-015 AC-8: keeps private-use characters of the source, even ones that look like a mark', async () => {
    const low = String.fromCharCode(0xe000);
    const text = `${low}7${low}x`;
    const {typ, lineMap} = await run(`${text}\n\n# H`);
    expect(typ).toContain(text);
    expect(lineMap.map((e) => e.sourceLine)).toEqual([1, 3]);
  });

  it('US-015 AC-8: has no entry for the body of a footnote definition or for an inline footnote', async () => {
    const {lineMap} = await run('Para^[inline]\n\n[^n]: def');
    expect(lineMap.map((e) => e.sourceLine)).toEqual([1]);
  });

  it('US-015 AC-8: is in output order, with 1-based lines that point at the text of the entry', async () => {
    const {typ, lineMap} = await run(COMPOSED_NOTE);
    const lines = typ.split('\n');
    expect(lineMap.map((e) => e.typLine)).toEqual(
      [...lineMap.map((e) => e.typLine)].sort((a, b) => a - b),
    );
    expect(lines[(lineMap[0]?.typLine ?? 0) - 1]).toBe('= Rules <h-rules>');
    expect(lines[(lineMap[2]?.typLine ?? 0) - 1]).toBe(
      '== Tessera <h-tessera>',
    );
    for (const entry of lineMap) {
      expect(entry.typLine).toBeGreaterThanOrEqual(1);
      expect(entry.typLine).toBeLessThanOrEqual(lines.length);
      expect(entry.sourceLine).toBeGreaterThanOrEqual(1);
    }
  });

  it('US-015 AC-8: gives the same map for a CRLF source', async () => {
    const lf = await run(MIXED);
    const crlf = await run(MIXED.replace(/\n/g, '\r\n'));
    expect(crlf.lineMap).toEqual(lf.lineMap);
  });

  it('US-015 AC-8: has an empty map for a note without blocks', async () => {
    expect((await run('')).lineMap).toEqual([]);
  });
});

describe('US-015 AC-9 determinism and purity', () => {
  it('US-015 AC-9: returns equal results for equal input', async () => {
    const a = await run(COMPOSED_NOTE);
    const b = await run(COMPOSED_NOTE);
    expect(b).toEqual(a);
  });

  it('US-015 AC-9: gives the same typ, assets and warnings for CRLF and LF sources', async () => {
    const note = `${COMPOSED_NOTE}\n\n![](gone.png)\n\n[[x]]\n\n\`\`\`\ncode  \n\`\`\`\n`;
    const lf = await run(note);
    const crlf = await run(note.replace(/\n/g, '\r\n'));
    expect(crlf.typ).toBe(lf.typ);
    expect(crlf.assets).toEqual(lf.assets);
    expect(crlf.warnings).toEqual(lf.warnings);
  });

  it('US-015 AC-9: does not depend on the order in which the lookups answer', async () => {
    const note = '![[a.png]]\n\n![](assets/b.png)\n\n![](assets/c.png)';
    const files = [
      NOTE_PATH,
      'Sample/assets/a.png',
      'Sample/assets/b.png',
      'Sample/assets/c.png',
    ];
    const forward = new FakeIndex(files);
    forward.delay = (path) =>
      path.endsWith('a.png') ? 15 : path.endsWith('b.png') ? 8 : 0;
    const reverse = new FakeIndex(files);
    reverse.delay = (path) =>
      path.endsWith('a.png') ? 0 : path.endsWith('b.png') ? 8 : 15;
    const x = await run(note, {assets: forward}, files);
    const y = await run(note, {assets: reverse}, files);
    expect(y).toEqual(x);
    expect(x.assets.map((a) => a.to)).toEqual([
      'assets/a.png',
      'assets/b.png',
      'assets/c.png',
    ]);
  });

  it('US-015 AC-9: does not change the input (the file list and the settings)', async () => {
    const files = [...COMPOSED_FILES];
    const settings = JSON.parse(JSON.stringify(SETTINGS)) as typeof SETTINGS;
    await run(COMPOSED_NOTE, {settings}, files);
    expect(files).toEqual(COMPOSED_FILES);
    expect(settings).toEqual(SETTINGS);
  });

  it('US-015 AC-9: core/convert imports only from src/core and markdown-it packages and reads no clock, locale, environment or random source', () => {
    const dir = 'src/core/convert';
    const files = readdirSync(dir).filter((f) => f.endsWith('.ts'));
    expect(files.length).toBeGreaterThan(0);
    for (const file of files) {
      const text = readFileSync(join(dir, file), 'utf8');
      const modules = [
        ...text.matchAll(/(?:from|import)\s+['"]([^'"]+)['"]/g),
      ].map((m) => m[1] as string);
      for (const module of modules) {
        expect(
          module.startsWith('./') ||
            module.startsWith('../') ||
            module.startsWith('markdown-it'),
          `${file}: ${module}`,
        ).toBe(true);
        expect(module).not.toMatch(/^(obsidian|electron|node:|fs$|path$)/);
      }
      expect(text, file).not.toMatch(
        /\bDate\b|Math\.random|process\.|toLocale|Intl\./,
      );
    }
  });
});

describe('US-015 AC-11 edge inputs', {timeout: 60_000}, () => {
  const inputs = [
    '**unclosed bold',
    'text ^[unclosed note',
    '[[unclosed link',
    '<!-- unclosed comment',
    'a ~~b `c *d',
    '[x](',
    '![](',
    '[^',
    '| a | b |\n|--|',
    '- a\n  - b\n\t- c\n\n   - d\n1. x\n   2. y',
    '\u0000\u0001\u0007\u001b[31m\u007f text   ​',
  ];
  for (const source of inputs) {
    it(`US-015 AC-11: returns a result for ${JSON.stringify(source).slice(0, 40)}`, async () => {
      const result = await run(source);
      expect(result.typ.startsWith(HEADER)).toBe(true);
      expect(result.typ.endsWith('\n')).toBe(true);
      expect(result.typ).not.toContain('\r');
      expect(Array.isArray(result.warnings)).toBe(true);
    });
  }

  it('US-015 AC-11: returns a result for a single line of 200000 characters, in reasonable time', async () => {
    const started = Date.now();
    const result = await run('a'.repeat(200_000));
    expect(result.typ.length).toBeGreaterThan(200_000);
    expect(Date.now() - started).toBeLessThan(10_000);
  });

  it('US-015 AC-11: returns a result for 200000 characters of markup characters', async () => {
    const result = await run('*_'.repeat(100_000));
    expect(result.typ.endsWith('\n')).toBe(true);
  });

  it('US-015 AC-11: a letter outside the BMP before a strong mark gives the function form, a symbol outside the BMP the delimiters', async () => {
    const letter = String.fromCodePoint(0x1d400);
    const symbol = String.fromCodePoint(0x1f600);
    const after = await run(`${letter}**b**`);
    expect(after.typ).toContain(`${letter}#strong[b]`);
    const apart = await run(`${symbol}**b**`);
    expect(apart.typ).toContain(`${symbol}*b*`);
  });

  it('US-015 AC-11: returns a result for the sample note', async () => {
    const real = readSample('Book.md');
    const result = await run(real);
    expect(result.typ.length).toBeGreaterThan(real.length / 2);
  });
});

/** Every `kind: 'a' | 'b'` of the tree types. */
function kindsOfTree(): Set<string> {
  const types = readFileSync('src/core/parse/types.ts', 'utf8');
  return new Set(
    [...types.matchAll(/kind: ((?:'[a-z-]+'(?: \| )?)+);/g)]
      .flatMap((m) => [...(m[1] ?? '').matchAll(/'([a-z-]+)'/g)])
      .map((m) => m[1] as string),
  );
}

