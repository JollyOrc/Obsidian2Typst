// US-015 — conversion pipeline (unit, pure core): result shape, preamble,
// settings, spacing, the composed example, warnings. Source of truth:
// docs/user-stories/US-015-conversion-pipeline.md. The line map, determinism,
// edge inputs and node coverage are in us-015-line-map-and-edges.test.ts, the
// vault lookup and asset plan in us-015-asset-index.test.ts.
import {describe, expect, it} from 'vitest';
import {
  PREAMBLE_RULES,
  checkPreambleRules,
  renderPreamble,
  type PreambleRule,
} from '../../src/core/convert/preamble';
import {FIT_IMAGE_HELPER} from '../../src/core/emit';
import {
  A5_PRINT,
  COMPOSED_FILES,
  COMPOSED_NOTE,
  FakeIndex,
  SETTINGS,
  run,
} from '../support/convert';

const HEADER =
  '// Generated by Obsidian2Typst from "Rules.md". Regenerated on every export.';
const PAGE =
  '#set page(width: 154mm, height: 216mm, margin: (top: 21mm, bottom: 25mm, inside: 23mm, outside: 18mm))';
const HIGHLIGHT = '#set highlight(fill: rgb("#ffeb3b"))';
const NUMBERING = '#set heading(numbering: "1.1")';
const RESTART =
  '#show heading.where(level: 1): it => { counter(footnote).update(0); it }';
const PREAMBLE = [HEADER, PAGE, HIGHLIGHT, NUMBERING, RESTART];

const COMPOSED_TYP =
  [
    ...PREAMBLE,
    FIT_IMAGE_HELPER,
    '',
    '= Rules <h-rules>',
    '',
    'Intro with *bold*, a #link("https://example.org")[link]#footnote[#link("https://example.org")] and a #link(<h-tessera>)[Tessera] reference#footnote[See the table.];.',
    '',
    '== Tessera <h-tessera>',
    '',
    '- Strike',
    '- Parry',
    '',
    '#figure(fit-image("assets/map.png"), caption: [Map], numbering: none)',
    '',
    '#table(',
    '  columns: 2,',
    '  align: (left, right),',
    '  table.header([Weapon], [Cost]),',
    '  [Sword], [10],',
    ')',
  ].join('\n') + '\n';

describe('US-015 AC-1 shape of the result', () => {
  it('US-015 AC-1: returns {typ, assets, warnings, lineMap}', async () => {
    const result = await run(COMPOSED_NOTE);
    expect(Object.keys(result).sort()).toEqual([
      'assets',
      'lineMap',
      'typ',
      'warnings',
    ]);
    expect(typeof result.typ).toBe('string');
    expect(Array.isArray(result.assets)).toBe(true);
    expect(Array.isArray(result.warnings)).toBe(true);
    expect(Array.isArray(result.lineMap)).toBe(true);
  });

  it('US-015 AC-1: returns a promise and reads the vault only through the injected index', async () => {
    const index = new FakeIndex(COMPOSED_FILES);
    const promise = run(COMPOSED_NOTE, {assets: index});
    expect(promise).toBeInstanceOf(Promise);
    await promise;
    expect(index.reads).toEqual(['Sample/assets/map.png']);
  });

  it('US-015 AC-1: passes the injected fonts on, so that the task-list marker depends on them', async () => {
    const asked: [string, number][] = [];
    const fonts = {
      hasGlyph: (family: string, codePoint: number) => {
        asked.push([family, codePoint]);
        return true;
      },
    };
    const withFonts = await run('- [ ] a\n- [x] b', {fonts});
    expect(asked.length).toBeGreaterThan(0);
    const without = await run('- [ ] a\n- [x] b');
    expect(without.typ).not.toBe(withFonts.typ);
  });
});

describe('US-015 AC-2 skeleton and fixed order', () => {
  it('US-015 AC-2: emits header, page, highlight, heading numbering, footnote restart, blank line, body, in this order', async () => {
    const {typ} = await run('# Title');
    expect(typ).toBe([...PREAMBLE, '', '= Title <h-title>', ''].join('\n'));
  });

  it('US-015 AC-2: without a template there is no import line', async () => {
    const {typ} = await run('x');
    expect(typ).not.toContain('#import');
  });

  it('US-015 AC-2: with a template the import line is line 2, before every generated rule', async () => {
    const {typ} = await run('x', {settings: {...SETTINGS, template: true}});
    expect(typ.split('\n').slice(0, 3)).toEqual([
      HEADER,
      '#import "template.typ": *',
      PAGE,
    ]);
    expect(typ.split('#import "template.typ": *').length).toBe(2);
  });

  it('US-015 AC-2: headingNumbering none gives numbering: none and keeps the footnote restart rule', async () => {
    const {typ} = await run('x', {
      settings: {...SETTINGS, headingNumbering: 'none'},
    });
    expect(typ).toContain('#set heading(numbering: none)');
    expect(typ).not.toContain(NUMBERING);
    expect(typ).toContain(RESTART);
  });

  it('US-015 AC-2: a pattern for the numbering is written as a Typst string', async () => {
    const {typ} = await run('x', {
      settings: {...SETTINGS, headingNumbering: '(a.1)'},
    });
    expect(typ).toContain('#set heading(numbering: "(a.1)")');
  });

  it('US-015 AC-2: every rule appears exactly once, also in the composed example', async () => {
    const {typ} = await run(COMPOSED_NOTE);
    for (const rule of [PAGE, HIGHLIGHT, NUMBERING, RESTART]) {
      expect(typ.split(rule).length - 1, rule).toBe(1);
    }
    expect(typ.split('#let fit-image').length - 1).toBe(1);
  });

  it('US-015 AC-2: the image helper rule is written only when a found image is placed', async () => {
    const withImage = await run('![](assets/map.png)');
    expect(withImage.typ).toContain(FIT_IMAGE_HELPER);
    const none = await run('# No image');
    expect(none.typ).not.toContain('fit-image');
    const missing = await run('![](assets/gone.png)');
    expect(missing.warnings.map((w) => w.code)).toEqual(['ASSET_MISSING']);
    expect(missing.typ).not.toContain('#let fit-image');
    expect(missing.typ).toContain('Missing image');
  });

  it('US-015 AC-2: the image helper stays in the preamble, before the body, also when the first image comes late', async () => {
    const {typ} = await run('# A\n\ntext\n\n![](assets/map.png)');
    expect(typ.indexOf('#let fit-image')).toBeLessThan(typ.indexOf('= A'));
  });

  it('US-015 AC-2: the registry has these ids and order numbers', () => {
    expect(
      PREAMBLE_RULES.map((rule) => [rule.id, rule.order]).sort(
        (a, b) => Number(a[1]) - Number(b[1]),
      ),
    ).toEqual([
      ['template-import', 20],
      ['page', 30],
      ['text-and-fonts', 40],
      ['page-furniture', 45],
      ['page-refs', 47],
      ['highlight', 50],
      ['heading-numbering', 60],
      ['footnote-restart', 70],
      ['fit-image', 80],
      ['callouts', 85],
      ['glossary', 86],
      ['cover', 90],
    ]);
  });

  it('US-015 AC-2: the registry is valid', () => {
    expect(checkPreambleRules(PREAMBLE_RULES)).toEqual([]);
  });

  const rule = (id: string, order: number): PreambleRule => ({
    id,
    order,
    render: () => id,
  });

  it('US-015 AC-2: checkPreambleRules reports two rules with the same id, two with the same order number, and an id that is registered twice', () => {
    expect(checkPreambleRules([rule('a', 1), rule('a', 2)])).toHaveLength(1);
    expect(checkPreambleRules([rule('a', 1), rule('b', 1)])).toHaveLength(1);
    expect(
      checkPreambleRules([rule('a', 1), rule('a', 1), rule('b', 3)]).length,
    ).toBeGreaterThanOrEqual(1);
    expect(checkPreambleRules([rule('a', 1), rule('b', 2)])).toEqual([]);
  });

  it('US-015 AC-2: renderPreamble refuses an invalid registry and writes valid rules sorted by order number, skipping rules that return null', () => {
    const context = {noteName: 'n', settings: SETTINGS, usesFitImage: false};
    expect(() => renderPreamble([rule('a', 1), rule('b', 1)], context)).toThrow(
      /order/,
    );
    expect(
      renderPreamble(
        [rule('c', 3), {id: 'x', order: 2, render: () => null}, rule('a', 1)],
        context,
      ),
    ).toEqual(['a', 'c']);
  });

  it('US-015 AC-2: the header comment names the note and cannot be broken out of by its name', async () => {
    const {typ} = await run('x', {noteName: 'A "B"\n#panic("x")\r#oops'});
    const lines = typ.split('\n');
    expect(lines[0]?.startsWith('// ')).toBe(true);
    expect(lines[1]).toBe(PAGE);
    expect(typ).not.toMatch(/^#panic/m);
    expect(typ).not.toMatch(/^#oops/m);
    expect(typ).not.toContain('\r');
  });

  it('US-015 AC-2: no line break of Typst reaches the header comment (VT, FF, NEL, LS, PS)', async () => {
    for (const code of [0x0b, 0x0c, 0x85, 0x2028, 0x2029]) {
      const br = String.fromCharCode(code);
      const {typ} = await run('x', {noteName: `a${br}#panic("x")${br}b`});
      const first = typ.split('\n')[0] ?? '';
      expect(first.startsWith('// '), String(code)).toBe(true);
      expect(first).not.toContain(br);
      expect(first).toContain('a #panic("x") b.md');
    }
  });

  it('US-015 AC-9: the header comment contains no date, version or absolute path', async () => {
    const {typ} = await run('x', {
      notePath: '/Users/me/Vault/Sample/Rules.md',
    });
    expect(typ.split('\n')[0]).toBe(HEADER);
    expect(typ).not.toContain('/Users/me');
    expect(typ).not.toMatch(/\d{4}-\d{2}-\d{2}/);
  });
});

describe('US-015 AC-3 settings', () => {
  it('US-015 AC-3: missing optional fields take the built-in defaults', async () => {
    const note = '# A\n\n[x](https://x.org)';
    const defaults = await run(note);
    const explicit = await run(note, {
      settings: {
        page: A5_PRINT,
        highlightColor: '#ffeb3b',
        headingNumbering: '1.1',
        externalLinkFootnotes: true,
        template: false,
      },
    });
    expect(defaults).toEqual(explicit);
  });

  it('US-015 AC-3: a chosen highlight colour is written as given', async () => {
    const {typ} = await run('x', {
      settings: {...SETTINGS, highlightColor: '#FF0000'},
    });
    expect(typ).toContain('#set highlight(fill: rgb("#FF0000"))');
    expect(typ).not.toContain('#ffeb3b');
  });

  it('US-015 AC-3: externalLinkFootnotes false leaves the address out of a footnote', async () => {
    const {typ} = await run('[x](https://x.org)', {
      settings: {...SETTINGS, externalLinkFootnotes: false},
    });
    expect(typ).toContain('#link("https://x.org")[x]');
    expect(typ).not.toContain('#footnote');
  });

  it('US-015 AC-3: the page geometry decides the page line', async () => {
    const {typ} = await run('x', {
      settings: {
        page: {
          pageWidth: 210,
          pageHeight: 297,
          facingPages: false,
          slug: 0,
          margins: {top: 20, bottom: 20, inside: 20, outside: 20},
        },
      },
    });
    expect(typ).toContain(
      '#set page(width: 210mm, height: 297mm, margin: (top: 20mm, bottom: 20mm, left: 20mm, right: 20mm))',
    );
  });

  for (const color of [
    '#fff',
    'red',
    '#ffeb3bX',
    '',
    '#ffeb3',
    'ffeb3b',
    '#ffeb3b ',
    '#ggg000',
  ]) {
    it(`US-015 AC-3: throws a TypeError for the highlight colour ${JSON.stringify(color)}`, async () => {
      await expect(
        run('x', {settings: {...SETTINGS, highlightColor: color}}),
      ).rejects.toThrow(TypeError);
    });
  }

  it('US-015 AC-3: throws a TypeError without page geometry', async () => {
    await expect(
      run('x', {settings: {} as unknown as typeof SETTINGS}),
    ).rejects.toThrow(/page geometry/);
    await expect(
      run('x', {settings: {page: null} as unknown as typeof SETTINGS}),
    ).rejects.toThrow(TypeError);
  });

  it('US-015 AC-3: accepts upper and lower case hex digits', async () => {
    for (const color of ['#abcdef', '#ABCDEF', '#a1B2c3']) {
      await expect(
        run('x', {settings: {...SETTINGS, highlightColor: color}}),
      ).resolves.toBeDefined();
    }
  });
});

describe('US-015 AC-4 block spacing and file end', () => {
  it('US-015 AC-4: separates top-level blocks by exactly one blank line and ends with one newline', async () => {
    const {typ} = await run('# A\n\npara\n\n\n\n- x\n\n---\n\n> q\n');
    const body = typ.slice(typ.indexOf('= A'));
    expect(body).not.toMatch(/\n\n\n/);
    expect(typ.endsWith('\n')).toBe(true);
    expect(typ.endsWith('\n\n')).toBe(false);
  });

  it('US-015 AC-4: uses LF only, even for a CRLF source', async () => {
    const {typ} = await run(COMPOSED_NOTE.replace(/\n/g, '\r\n'));
    expect(typ).not.toContain('\r');
  });

  it('US-015 AC-4: has no trailing spaces on a generated line, hard breaks and trailing blanks of the source included', async () => {
    const {typ} = await run('a  \nb   \n\nc \n\n- d  \n- e\t\n');
    expect(typ).not.toMatch(/[ \t]$/m);
  });

  it('US-015 AC-4: has no trailing space where a dropped comment or an HTML block leaves one', async () => {
    const {typ} = await run('a <!-- c -->\nb\n\n<div>\nx  \n</div>\n');
    expect(typ).not.toMatch(/[ \t]$/m);
  });

  it('US-015 AC-4: keeps the trailing spaces inside a code block, which is raw and exact', async () => {
    const {typ} = await run('```js\nlet x = 1;  \n```\n');
    expect(typ).toContain('let x = 1;  \n```');
  });

  it('US-015 AC-4: yields header and preamble only, with the final newline, for an empty source, frontmatter only and only comments', async () => {
    const expected = PREAMBLE.join('\n') + '\n';
    for (const source of [
      '',
      '\n',
      '---\ntitle: x\n---\n',
      '<!-- only a comment -->',
      '---\ntitle: x\n---\n\n<!-- a -->\n\n<!-- b -->\n',
    ]) {
      const {typ} = await run(source);
      expect(typ, JSON.stringify(source)).toBe(expected);
    }
  });
});

describe('US-015 AC-5 composed example', () => {
  it('US-015 AC-5: produces exactly the typ of the composed example', async () => {
    const {typ} = await run(COMPOSED_NOTE);
    expect(typ).toBe(COMPOSED_TYP);
  });

  it('US-015 AC-5: the note without the image has the same text without the helper lines', async () => {
    const note = COMPOSED_NOTE.replace('![Map](assets/map.png)\n\n', '');
    const {typ} = await run(note);
    const expected = COMPOSED_TYP.replace(`${FIT_IMAGE_HELPER}\n`, '').replace(
      '#figure(fit-image("assets/map.png"), caption: [Map], numbering: none)\n\n',
      '',
    );
    expect(typ).toBe(expected);
  });

  it('US-015 AC-5: has no warnings and leaves no text of the definition at its own place', async () => {
    const result = await run(COMPOSED_NOTE);
    expect(result.warnings).toEqual([]);
    expect(result.typ.split('See the table.').length - 1).toBe(1);
  });

  it('US-015 AC-5: gives the assets of the example', async () => {
    const result = await run(COMPOSED_NOTE);
    expect(result.assets).toEqual([
      {from: 'Sample/assets/map.png', to: 'assets/map.png'},
    ]);
  });
});

describe('US-015 AC-7 warnings', () => {
  it('US-015 AC-7: orders warnings by source line, then by order of detection', async () => {
    const note = [
      '# A', // 1
      '', // 2
      '### C', // 3 (HEADING_LEVEL_SKIPPED)
      '', // 4
      '[[Nowhere]] and ![](gone.png)', // 5 (link, then asset)
      '', // 6
      'x[^u]', // 7 (FOOTNOTE_UNDEFINED)
    ].join('\n');
    const {warnings} = await run(note);
    expect(warnings.map((w) => w.code)).toEqual([
      'HEADING_LEVEL_SKIPPED',
      'LINK_UNRESOLVED',
      'ASSET_MISSING',
      'FOOTNOTE_UNDEFINED',
    ]);
    expect(warnings.map((w) => w.line)).toEqual([3, 5, 5, 7]);
  });

  it('US-015 AC-7: returns the warnings and does not throw; strict mode is the shell’s business', async () => {
    const result = await run('![](gone.png)\n\n[[x]]');
    expect(result.warnings.length).toBe(2);
    expect(result.typ.length).toBeGreaterThan(0);
  });

  it('US-015 AC-7: every warning is {code, message, line} with a line of the source file, frontmatter counted', async () => {
    const {warnings} = await run('---\ntitle: x\n---\n\n![](gone.png)');
    expect(warnings).toEqual([
      {code: 'ASSET_MISSING', message: expect.any(String), line: 5},
    ]);
  });
});
