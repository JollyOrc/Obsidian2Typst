afterEach(() => {
  vi.useRealTimers();
});

describe('US-008 AC-15 what the command refuses', () => {
  it('US-008 AC-15: asks to open a note when none is open', async () => {
    const r = await rig();
    r.openNote.path = null;
    expect(await r.command()).toEqual({status: 'no-note'});
    expect(r.notices).toEqual(['Open a note to export it']);
    expect(r.chosen).toEqual([]);
    expect(r.requests).toEqual([]);
  });

  it('US-008 AC-15: refuses a note in the presets folder, also in a subfolder, but not one of a similar name', async () => {
    const r = await rig();
    for (const path of [A5, `${FOLDER}/sub/Deep.md`]) {
      r.openNote.path = path;
      expect(await r.command()).toEqual({status: 'presets-note'});
    }
    expect(r.notices).toEqual([
      'Presets are not exported',
      'Presets are not exported',
    ]);
    expect(r.requests).toEqual([]);

    r.texts.set('Obsidian2Typst/presets-old/Note.md', '# Old');
    r.openNote.path = 'Obsidian2Typst/presets-old/Note.md';
    expect((await r.command()).status).toBe('exported');
  });

  it('US-008 AC-4: refuses when the active preset is invalid, with the error, and does not switch the preset', async () => {
    const r = await rig({
      [A5]: TAB,
      [A4]: BUILTIN_PRESET_TEXTS['A4 digital'],
    });
    expect(await r.command()).toEqual({status: 'invalid-preset'});
    expect(r.notices).toEqual([
      'Preset "A5 print" is invalid: Tabs are not allowed as indentation (line 4)',
    ]);
    expect(r.data.activePreset).toBe('A5 print');
    expect(r.chosen).toEqual([]);
    expect(r.requests).toEqual([]);
  });

  it('US-008 AC-15: says so when there is no preset at all', async () => {
    const r = await rig({});
    expect(await r.command()).toEqual({status: 'no-preset'});
    expect(r.notices).toEqual([
      'There is no preset; create one in the settings of Obsidian2Typst',
    ]);
  });
});

describe('US-008 AC-15 folder, remembered per preset', () => {
  it('US-007 AC-1: the command Obsidian2Typst: Export current note asks for a folder and remembers it per preset', async () => {
    const r = await rig();
    r.data.lastExportFolders = {'A5 print': '/old'};
    r.folderAnswer.value = '/new';
    const result = await r.command();
    expect(result).toEqual({status: 'exported'});
    expect(r.chosen).toEqual(['/old']);
    expect(r.saved).toEqual([['A5 print', '/new']]);
    expect(first(r).exportDir).toBe('/new');

    r.data.activePreset = 'A4 digital';
    r.folderAnswer.value = '/digital';
    await r.command();
    expect(r.chosen).toEqual(['/old', null]);
    expect(r.data.lastExportFolders).toEqual({
      'A5 print': '/new',
      'A4 digital': '/digital',
    });
  });

  it('US-008 AC-15: a cancelled folder dialog starts nothing and remembers nothing', async () => {
    const r = await rig();
    r.folderAnswer.value = null;
    expect(await r.command()).toEqual({status: 'cancelled'});
    expect(r.saved).toEqual([]);
    expect(r.requests).toEqual([]);
    expect(r.notices).toEqual([]);
  });

  it('US-008 AC-15: returns the result of the export run', async () => {
    const r = await rig();
    r.result.value = {status: 'compile-error'};
    expect(await r.command()).toEqual({status: 'compile-error'});
  });
});

describe('US-008 AC-15 what the export run gets', () => {
  it('US-008 AC-15: hands over the typ of the active preset, the assets, no warnings and the settings of US-006', async () => {
    const r = await rig();
    r.data.strictMode = true;
    r.data.warningsNoteFolder = 'Reports';
    await r.command();
    const request = first(r);
    expect(request.noteName).toBe('Rules');
    expect(request.source).toEqual({path: NOTE, inVault: true});
    const lines = request.typ.split('\n');
    expect(lines[0]).toBe(HEADER);
    expect(lines[1]).toBe(A5_PAGE);
    expect(request.uses).toEqual([
      {from: 'Sample/assets/map.png', to: 'assets/map.png'},
    ]);
    expect(request.warnings).toEqual([]);
    expect(request.template).toBeNull();
    expect(request.settings).toEqual({
      strictMode: true,
      warningsNoteFolder: 'Reports',
    });
  });

  it('US-008 AC-15: reads the head of the image file only, and gives the run a reader for the bytes', async () => {
    const r = await rig();
    await r.command();
    expect(r.heads).toEqual(['Sample/assets/map.png']);
    const bytes = await first(r).readAsset('Sample/assets/map.png');
    expect(bytes).toEqual(standIn('Sample/assets/map.png'));
  });

  it('US-008 AC-15: drops the frontmatter of the note and exports the rest', async () => {
    const r = await rig(undefined, '---\ntitle: x\n---\n\n# Title\n');
    await r.command();
    expect(first(r).typ).toContain('= Title <h-title>');
    expect(first(r).typ).not.toContain('title: x');
  });

  it('US-008 AC-12: uses the first preset in alphabetical order when the stored active preset no longer exists', async () => {
    const r = await rig();
    r.data.activePreset = 'Gone';
    await r.command();
    expect(first(r).typ.split('\n')[1]).toBe(A4_PAGE);
    expect(r.saved).toEqual([['A4 digital', '/out']]);
  });
});

describe('US-008 AC-14 the Defaults and the note name reach the export', () => {
  it('US-008 AC-14: a value from the Defaults that the preset does not set is in the typ', async () => {
    const r = await rig();
    r.data.defaults = {headingNumbering: 'a.1'};
    await r.command();
    expect(first(r).typ).toContain('numbering: "a.1"');
  });

  it('US-008 AC-4: refuses when the Defaults made the preset invalid since the last check, with the error', async () => {
    const r = await rig({[A5]: '---\nschemaVersion: 1\n---\n'});
    r.data.defaults = {
      page: {trimSize: 'A6', margins: {inside: 40, outside: 40}},
    };
    expect(await r.command()).toEqual({status: 'invalid-preset'});
    expect(r.notices).toEqual([
      'Preset "A5 print" is invalid: Text block would be only 20 mm wide (minimum 30 mm)',
    ]);
    expect(r.requests).toEqual([]);
  });

  it('US-008 AC-15: takes the note name without the extension in any case (.md, .MD)', async () => {
    const r = await rig();
    r.texts.set('Sample/Book.MD', '# Book');
    r.openNote.path = 'Sample/Book.MD';
    await r.command();
    expect(first(r).noteName).toBe('Book');
  });
});

describe('US-008 AC-9 to AC-11 the template', () => {
  const withTemplate = (extra = ''): Record<string, string> => ({
    [A5]: `---\nschemaVersion: 1\ntemplate: ${TEMPLATE}\n${extra}---\n`,
    [A4]: BUILTIN_PRESET_TEXTS['A4 digital'],
  });

  it('US-008 AC-9: hands over the template text and writes the import before any generated rule', async () => {
    const r = await rig(withTemplate());
    r.texts.set(TEMPLATE, '#let accent = rgb("#336699")\n');
    await r.command();
    const request = first(r);
    expect(request.template).toBe('#let accent = rgb("#336699")\n');
    expect(request.typ.split('\n')[1]).toBe('#import "template.typ": *');
    expect(request.warnings).toEqual([]);
  });

  it('US-008 AC-9: takes the template of the Defaults when the preset has none, and the one of the preset over it', async () => {
    const r = await rig();
    r.data.defaults = {template: 'Styles/default.typ'};
    r.texts.set('Styles/default.typ', '#let d = 1\n');
    await r.command();
    expect(first(r).template).toBe('#let d = 1\n');

    const own = await rig(withTemplate());
    own.data.defaults = {template: 'Styles/default.typ'};
    own.texts.set('Styles/default.typ', '#let d = 1\n');
    own.texts.set(TEMPLATE, '#let own = 1\n');
    await own.command();
    expect(first(own).template).toBe('#let own = 1\n');
  });

  it('US-008 AC-11: continues without the import and reports TEMPLATE_MISSING when the template file does not exist', async () => {
    const r = await rig(withTemplate(), 'Intro\n\n![](gone.png)');
    await r.command();
    const request = first(r);
    expect(request.template).toBeNull();
    expect(request.typ).not.toContain('#import');
    expect(request.warnings.map((w) => w.code)).toEqual([
      'TEMPLATE_MISSING',
      'ASSET_MISSING',
    ]);
    expect(request.warnings[0]).toEqual({
      code: 'TEMPLATE_MISSING',
      message: `Template "${TEMPLATE}" does not exist; the export continues without it`,
      line: 0,
    });
  });

  it('US-008 AC-10: reports TEMPLATE_SHADOWS_BUILTIN and still imports the template', async () => {
    const r = await rig(withTemplate());
    r.texts.set(TEMPLATE, '#let a = 1\n\n#let quote(body) = block(body)\n');
    await r.command();
    const request = first(r);
    expect(request.template).toContain('#let quote(body)');
    expect(request.typ.split('\n')[1]).toBe('#import "template.typ": *');
    expect(request.warnings).toEqual([
      {
        code: 'TEMPLATE_SHADOWS_BUILTIN',
        message:
          'Template line 3 defines "quote", which shadows a Typst built-in',
        line: 0,
      },
    ]);
  });
});

describe('US-008 AC-7 and AC-12 presets are read, never written', () => {
  it('US-008 AC-7: leaves preset notes byte-identical after an export or preview', async () => {
    const r = await rig();
    const before = new Map(r.vault.files);
    const writes = [...r.vault.writes];
    await r.command();
    r.data.activePreset = 'A4 digital';
    await r.command();
    await vi.advanceTimersByTimeAsync(3000);
    expect(r.vault.files).toEqual(before);
    expect(r.vault.writes).toEqual(writes);
  });

  it('US-008 AC-12: switching the active preset changes the next export and the preview without restart', async () => {
    const r = await rig();
    await r.command();
    expect(first(r).typ.split('\n')[1]).toBe(A5_PAGE);
    r.data.activePreset = 'A4 digital';
    await r.command();
    expect(r.requests[1]?.typ.split('\n')[1]).toBe(A4_PAGE);
  });

  it('US-008 AC-3: an edit of the active preset note reaches the next export without restart', async () => {
    const r = await rig();
    r.vault.edit(
      A5,
      '---\nschemaVersion: 1\npage:\n  trimSize: A5\n  bleed: 5\n---\n',
    );
    await vi.advanceTimersByTimeAsync(2000);
    await r.command();
    expect(first(r).typ).toContain('#set page(width: 158mm, height: 220mm');
  });
});

const coverPreset = (...lines: string[]): Record<string, string> => ({
  [A5]: ['---', 'schemaVersion: 1', 'cover:', ...lines, '---', ''].join('\n'),
});
// US-019 AC-3: the built-in folios are on, so the export's cover pages carry
// `numbering: none`; any cover page starts with PAGE_HEAD.
const PAGE_RULE =
  '#page(margin: 0pt, header: none, footer: none, numbering: none)';
const PAGE_HEAD = '#page(margin: 0pt';

describe('US-011 the cover reaches the export', () => {
  it('US-011 AC-1: a cover file of the active preset is the first page, copied with the assets and read with the larger head', async () => {
    const r = await rig(
      coverPreset('  mode: file', '  file: "Covers/front.png"'),
      COMPOSED_NOTE,
      ['Covers/front.png'],
    );
    await r.command();
    expect(first(r).typ).toContain(`${PAGE_RULE}[`);
    expect(first(r).typ).toContain(
      '#image("assets/_external/front.png", width: 100%',
    );
    expect(first(r).uses).toContainEqual({
      from: 'Covers/front.png',
      to: 'assets/_external/front.png',
    });
    const at = r.heads.indexOf('Covers/front.png');
    expect(r.lengths[at]).toBe(IMAGE_SIZE_READ_BYTES);
    // the stand-in image of 30 x 20 px is read from its real header
    expect(first(r).warnings.map((w) => w.code)).toEqual(['COVER_CROPPED']);
  });

  it('US-011 AC-2: a note that starts with an image gets the cover of the built-in preset (mode auto)', async () => {
    const r = await rig(undefined, '![](assets/map.png)\n\n# Title\n');
    await r.command();
    expect(first(r).typ).toContain(`${PAGE_RULE}[`);
    expect(first(r).typ).not.toContain('fit-image(');
  });

  it('US-011 AC-3: mode none in the preset leaves the first image in the body', async () => {
    const r = await rig(
      coverPreset('  mode: none'),
      '![](assets/map.png)\n\n# Title\n',
    );
    await r.command();
    expect(first(r).typ).not.toContain(PAGE_HEAD);
    expect(first(r).typ).toContain('#fit-image("assets/map.png")');
  });

  it('US-011 AC-5: blankPageAfter of the preset adds the blank page before the counter reset', async () => {
    const r = await rig(
      coverPreset('  blankPageAfter: true'),
      '![](assets/map.png)\n\n# Title\n',
    );
    await r.command();
    expect(first(r).typ).toContain(`${PAGE_RULE}[]\n#counter(page).update(1)`);
  });

  it('US-011 AC-6: cropWarningPercent of the preset is the threshold', async () => {
    const lax = await rig(
      coverPreset('  cropWarningPercent: 60'),
      '![](assets/map.png)\n\n# Title\n',
    );
    await lax.command();
    expect(first(lax).warnings).toEqual([]);
    const strict = await rig(
      coverPreset('  cropWarningPercent: 5'),
      '![](assets/map.png)\n\n# Title\n',
    );
    await strict.command();
    expect(first(strict).warnings.map((w) => w.code)).toEqual([
      'COVER_CROPPED',
    ]);
  });

  it('US-011 AC-10: cover.back in the preset is reported once on export', async () => {
    const r = await rig(coverPreset('  back: "Covers/back.png"'));
    await r.command();
    expect(first(r).warnings).toEqual([
      {
        code: 'COVER_BACK_UNSUPPORTED',
        message: 'cover.back is not supported yet and is ignored',
        line: 0,
      },
    ]);
  });

  it('US-011 AC-1: a cover in the Defaults is not used (preset notes only)', async () => {
    const r = await rig();
    r.data.defaults = {
      cover: {mode: 'file', file: 'Covers/front.png'},
    } as never;
    await r.command();
    expect(first(r).typ).not.toContain(PAGE_HEAD);
  });

  it('US-011 AC-1: a preset with an invalid cover value is refused with its error and no export starts', async () => {
    const r = await rig(coverPreset('  mode: front'));
    expect(await r.command()).toEqual({status: 'invalid-preset'});
    expect(r.notices).toEqual([
      'Preset "A5 print" is invalid: cover.mode must be auto, file or none (line 4)',
    ]);
    expect(r.requests).toEqual([]);
  });
});
