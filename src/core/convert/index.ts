const GENERATED_BY = 'Generated by Obsidian2Typst' + ' from';

/** US-027: the contents lines and their place (`placeContents`). */
interface Contents {
  text: string;
  place: ContentsPlace;
}

/**
 * US-026 | AC-3 to AC-7, US-027 | AC-4 to AC-6: The lines of the book's
 * pages, or undefined when the note has no colophon, no back notes, no
 * contents and the signature is 0 (the output is then as before). The front
 * matter is a colophon or contents before the first chapter (US-027 AC-4); it
 * opens a no-header range that the first chapter's break closes; the first
 * chapter is `arranged.chapter`, else (an empty body) the back notes or the
 * end, so a range is never left open (the header pairs the ranges in order).
 * Contents in the body get their own pages and range before `place.at`
 * (before the back notes' own lines, or at the end before the padding). The
 * back notes get their new page and the padding; without them the padding
 * goes at the end.
 */
function bookLines(
  arranged: ArrangedParts,
  book: BookSettings,
  facingPages: boolean,
  folios: boolean,
  contents: Contents | null,
): BookLines | undefined {
  const {colophon, backNotes} = arranged;
  const frontContents = contents?.place.front === true ? contents : null;
  const bodyContents = contents?.place.front === false ? contents : null;
  const front = colophon !== null || frontContents !== null;
  if (
    !front &&
    bodyContents === null &&
    backNotes === null &&
    book.signature === 0
  ) {
    return undefined;
  }
  const before = new Map<BlockNode, string>();
  const add = (block: BlockNode, lines: string): void => {
    const known = before.get(block);
    before.set(block, known === undefined ? lines : `${known}\n${lines}`);
  };
  const noBreak = new Set<BlockNode>(arranged.partHeadings);
  let end: string | null = null;
  if (front) {
    if (colophon !== null) add(colophon, partStartLine());
    const chapterLines = chapterBreakLines(
      book.firstChapter,
      facingPages,
      folios,
    );
    const lead =
      frontContents === null
        ? chapterLines
        : `${frontContentsLines(frontContents.text, colophon !== null)}\n${chapterLines}`;
    const anchor = arranged.chapter;
    if (anchor === null) {
      if (backNotes === null) end = lead;
      else add(backNotes, lead);
    } else {
      add(anchor, lead);
      noBreak.add(anchor);
    }
  }
  if (bodyContents !== null) {
    const {at} = bodyContents.place;
    const lines = bodyContentsLines(
      bodyContents.text,
      at !== null && at !== backNotes,
    );
    if (at === null) end = end === null ? lines : `${end}\n${lines}`;
    else add(at, lines);
  }
  if (backNotes !== null) {
    add(backNotes, backNotesStartLines(book.signature));
    end = end === null ? '' : `${end}\n`;
    end += backNotesEndLines(book.signature);
  } else if (book.signature > 0) {
    end =
      end === null
        ? paddingEndLines(book.signature)
        : `${end}\n${paddingEndLines(book.signature)}`;
  }
  return {before, end, noBreak};
}

/**
 * US-028 | AC-1, AC-2, AC-3, AC-10 (decisions 1, 7): the image fit of the
 * body, or undefined at `images.minScale` 100 (the built-in; the output is
 * then as before). `min` is the percentage as a fraction (`0.7`); the blocks
 * of the back notes, from their first block to the end, never float.
 */
function imageFit(
  settings: ConvertSettings,
  arranged: ArrangedParts,
): {min: number; sides: boolean; noFloat: ReadonlySet<BlockNode>} | undefined {
  const {minScale} = {...DEFAULT_IMAGES, ...settings.images};
  if (minScale >= 100) return undefined;
  const start =
    arranged.backNotes === null
      ? arranged.blocks.length
      : arranged.blocks.indexOf(arranged.backNotes);
  return {
    min: minScale / 100,
    sides: settings.page.facingPages,
    noFloat: new Set(arranged.blocks.slice(start)),
  };
}

/** Typst's line breaks; none of them may reach the header comment. */
const LINE_BREAKS = new RegExp(
  `[${[0x0a, 0x0b, 0x0c, 0x0d, 0x85, 0x2028, 0x2029]
    .map((code) => '\\u' + code.toString(16).padStart(4, '0'))
    .join('')}]`,
  'g',
);

/** US-015 AC-3: throws a TypeError for settings that cannot be written. */
function checkSettings(settings: ConvertSettings): void {
  const page = (settings as Partial<ConvertSettings> | null | undefined)?.page;
  if (typeof page !== 'object' || page === null) {
    throw new TypeError('The settings need the page geometry (page)');
  }
  const color = settings.highlightColor ?? DEFAULT_HIGHLIGHT_COLOR;
  if (!/^#[0-9a-fA-F]{6}$/.test(color)) {
    throw new TypeError(
      `The highlight colour must be written #rrggbb, not ${JSON.stringify(color)}`,
    );
  }
}

/**
 * Removes the blanks at the end of every line except inside a raw code block,
 * which is exact (US-015 AC-4). A block opens with a line of three or more
 * backticks and an optional tag, and closes with the same number of backticks.
 */
function trimLines(lines: readonly string[]): string[] {
  let fence = 0;
  return lines.map((line) => {
    if (fence > 0) {
      if (line.trim() === '`'.repeat(fence)) fence = 0;
      else return line;
    } else {
      const open = /^\s*(`{3,})[A-Za-z0-9_-]*$/.exec(line);
      if (open !== null) fence = (open[1] ?? '').length;
    }
    return line.replace(/[ \t]+$/, '');
  });
}

/**
 * US-015 AC-1 to AC-13: converts one note.
 *
 * Reads the vault only through `input.assets`: first the heads of the files
 * whose name an image of the note uses, then everything else is pure. Throws a
 * TypeError for invalid settings; never for the content of a note, whose
 * problems become warnings. The same input gives the same result.
 */
export async function convert(input: ConvertInput): Promise<ConvertResult> {
  checkSettings(input.settings);
  const parsed = parse(input.source);
  // US-011: the image in first position is taken out of the body first.
  const plan = planCover(parsed.root, input.settings.cover);
  const {root} = plan;
  const coverFile = coverNames(plan.target);

  const callouts = input.settings.callouts ?? {};
  const heads = await readHeads(
    input.assets,
    new Set([
      ...referencedImageNames(root),
      ...coverFile,
      ...calloutIconNames(root, callouts),
    ]),
    coverFile,
  );
  const none = new Uint8Array(0);
  const resolver = createAssetResolver({
    notePath: input.notePath,
    files: new Map(
      input.assets.files.map((path) => [path, heads.get(path) ?? none]),
    ),
  });

  const ctx = new EmitContext();
  // US-017 AC-1 to AC-3: one heading index for the plan and the emitter, so
  // terms keep the labels the links use (AC-7). Pure; the warnings are
  // reported below, in their old place.
  const headings = indexHeadings(root, {dropImages: true});
  const glossary = findGlossary(
    root,
    headings,
    headingRuleTable(input.settings.headingRules),
  );
  // US-026 AC-1, AC-2, AC-8: the colophon before the body, the back notes
  // after it; one emitter call, so footnotes and labels stay one document.
  // Before the cover: a colophon changes the cover pages (AC-3).
  const arranged = arrangeParts(root, glossary.parts, input.settings.book);
  const book: BookSettings = {...DEFAULT_BOOK, ...input.settings.book};
  const folios = input.settings.pageFurniture?.folios === true;
  // US-027 AC-4, AC-5: the contents and their place; depth 0 (the built-in)
  // writes none and the output stays as it was.
  const toc = {...DEFAULT_TOC, ...input.settings.toc};
  const contents: Contents | null =
    toc.depth > 0
      ? {
          text: contentsLines(toc),
          place: placeContents(
            arranged,
            toc,
            (heading) => headings.byNode.get(heading)?.text,
          ),
        }
      : null;
  if (contents?.place.missing === true) {
    ctx.warn(
      'TOC_HEADING_MISSING',
      `The table of contents heading "${toc.heading}" is not in the note; the contents are at the default place`,
      0,
    );
  }
  // US-026 AC-3, US-027 AC-4: a colophon or contents before the first
  // chapter make the front matter.
  const frontMatter =
    arranged.colophon !== null || contents?.place.front === true;
  // US-011 AC-9: before the body, so that the cover gets its name first.
  const coverPages = resolveCover({
    target: plan.target,
    cover: input.settings.cover,
    resolver,
    heads,
    page: input.settings.page,
    ctx,
    numberingNone: folios,
    frontMatter,
  });
  // US-010 AC-2, AC-4: the families and sizes, before the body so that the
  // task-list rule asks the resolved body family.
  const fontInfo = input.fonts;
  const resolved =
    input.settings.fonts === undefined
      ? null
      : resolveFonts(
          input.settings.fonts,
          fontInfo?.resolve === undefined
            ? undefined
            : {resolve: fontInfo.resolve},
        );
  for (const w of resolved?.warnings ?? []) ctx.warn(w.code, w.message, w.line);
  const marks = createLineMarks(input.source);
  const recorder = createCalloutRecorder(callouts);
  for (const w of glossary.warnings) ctx.warn(w.code, w.message, w.line);
  for (const w of arranged.warnings) ctx.warn(w.code, w.message, w.line);
  // US-018 AC-2, AC-6: page numbers after links only with the switch and the
  // folios on, so the printed number exists; the rule only with a call.
  let pageRefCalls = 0;
  const pageRefs =
    input.settings.linkPageNumbers === true && folios
      ? {
          level: input.settings.linkPageLevel ?? 2,
          record: () => {
            pageRefCalls += 1;
          },
        }
      : undefined;
  // US-025 AC-2: breaks only when some level has a rule other than none.
  const rules = input.settings.breakBefore ?? {};
  const breaks = Object.values(rules).some((rule) => rule !== 'none')
    ? {rules, facingPages: input.settings.page.facingPages}
    : undefined;
  const facingPages = input.settings.page.facingPages;
  const pageLines = bookLines(arranged, book, facingPages, folios, contents);
  const gone = new Set(
    [...arranged.dropped].flatMap((heading) => {
      const label = headings.byNode.get(heading)?.label;
      return label === undefined ? [] : [label];
    }),
  );
  const body = emitBlocks(arranged.blocks, ctx, {
    hidden: arranged.hidden,
    gone,
    headings,
    glossary,
    callouts: recorder,
    bodyFamily: resolved?.fonts.body.family,
    externalLinkFootnotes: input.settings.externalLinkFootnotes ?? true,
    pageRefs,
    fonts: input.fonts,
    assets: resolver,
    mark: marks.mark,
    breaks,
    book: pageLines,
    unlistNested: contents !== null,
    fit: imageFit(input.settings, arranged),
  });
  // US-010 AC-5: characters of the source that their family lacks.
  if (resolved !== null && fontInfo !== undefined) {
    for (const w of checkGlyphs(root, resolved.fonts, fontInfo)) {
      ctx.warn(w.code, w.message, w.line);
    }
  }
  // US-016 AC-12, AC-13: fonts and icons of the used styles only, after the
  // body, so that icons share the body images' destination names (SCAR-011).
  const styleEntries: CalloutStyleEntry[] = [];
  const missingFamilies = new Set<string>();
  for (const [name, style] of recorder.used()) {
    let family = style.font.family;
    if (
      family !== null &&
      resolved !== null &&
      fontInfo?.resolve !== undefined
    ) {
      const found = fontInfo.resolve(family);
      if (found === null) {
        const key = family.toLowerCase();
        if (!missingFamilies.has(key)) {
          missingFamilies.add(key);
          ctx.warn(
            'FONT_MISSING',
            `Font "${family}" for callout ${name} was not found; "${resolved.fonts.body.family}" is used`,
            0,
          );
        }
      }
      family = found;
    }
    let icon: string | null = null;
    if (style.icon !== null) {
      const result = resolver.resolve({
        source: 'image',
        target: `/${style.icon}`,
        line: 0,
      });
      if (result.status === 'found' || result.status === 'ambiguous') {
        icon = result.path;
      } else {
        ctx.warn(
          'CALLOUT_ICON_MISSING',
          `Icon "${style.icon}" of callout style "${name}" ${
            result.status === 'missing' ? 'was not found' : 'is not an image'
          }; the box is drawn without it`,
          0,
        );
      }
    }
    styleEntries.push({name, style, family, icon});
  }
  const {lines, entries} = marks.extract(body);

  const name = input.noteName.replace(LINE_BREAKS, ' ');
  const header = `// ${GENERATED_BY} "${name}.md". Regenerated on every export.`;
  const preamble = [
    header,
    ...renderPreamble(PREAMBLE_RULES, {
      noteName: input.noteName,
      settings: input.settings,
      usesFitImage: ctx.fitImagePlaced,
      usesFitFlow: ctx.fitFlowPlaced,
      cover: coverPages,
      fonts: resolved === null ? null : emitFonts(resolved.fonts),
      callouts: calloutStylesRule(styleEntries),
      glossary: glossary.hasTerms ? GLOSSARY_HELPER : null,
      furniture: pageFurnitureRule(
        input.settings.pageFurniture,
        facingPages,
        // US-026 AC-6: the first chapter's break and the padding before the
        // back notes write the US-025 markers too.
        breaks !== undefined ||
          frontMatter ||
          (book.signature > 0 && arranged.backNotes !== null),
        {
          // US-026 AC-6, US-027 AC-6: the no-header ranges of the parts and
          // the contents.
          parts: pageLines !== undefined,
          front: !frontMatter ? null : book.romanFrontMatter ? 'roman' : 'none',
        },
      ),
      // US-018 AC-3: the word follows ` (` inside a content block.
      pageRefs:
        pageRefCalls > 0
          ? pageRefHelper(
              escapeMarkup(input.settings.linkPageWord ?? 'p.', {
                atBlockStart: false,
              }),
              // US-026 AC-10: the folio as printed, roman or arabic.
              frontMatter && book.romanFrontMatter,
            )
          : null,
    }),
  ].join('\n');

  const offset = preamble.split('\n').length + 1;
  const text = body === '' ? '' : `\n${trimLines(lines).join('\n')}\n`;
  return {
    typ: `${preamble}\n${text}`,
    assets: resolver.uses(),
    warnings: ctx.finish(),
    lineMap: entries.map((e) => ({
      typLine: e.typLine + offset,
      sourceLine: e.sourceLine,
    })),
  };
}
